fn config_command(config: &Config, args: &ConfigArgs) -> ZtResult<i32> {
    match args
        .command
        .as_ref()
        .unwrap_or(&ConfigCommand::Show(JsonArgs { json: false }))
    {
        ConfigCommand::Path => {
            println!("{}", config.config_path.display());
            Ok(0)
        }
        ConfigCommand::Show(args) => {
            if args.json {
                print_json(&config_json(config))?;
            } else {
                println!("host: {}", config.host);
                println!("transport: {}", config.transport.as_str());
                println!("picker: {}", config.picker.as_str());
                println!("remote_path: {}", config.remote_path);
                println!("connect_timeout: {}", config.connect_timeout);
                println!("ssh_options: {}", config.ssh_options.join(", "));
                println!("no_input: {}", config.no_input);
                println!("config_path: {}", config.config_path.display());
                println!("config_loaded: {}", config.config_loaded);
            }
            Ok(0)
        }
        ConfigCommand::Init(args) => {
            if config.config_path.exists() && !args.force {
                return Err(ZtError::new(
                    format!(
                        "config already exists: {} (use --force to overwrite)",
                        config.config_path.display()
                    ),
                    2,
                ));
            }
            if let Some(parent) = config.config_path.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(&config.config_path, default_config_text())?;
            println!("{}", config.config_path.display());
            Ok(0)
        }
    }
}

fn remote_cmd(config: &Config, command: &str) -> String {
    format!("PATH={}; {command}", config.remote_path)
}

fn ssh_argv(config: &Config, batch: bool, tty: bool) -> Vec<String> {
    let mut args = vec!["ssh".to_string()];
    if tty {
        args.push("-t".to_string());
    }
    if batch {
        args.extend(["-o".to_string(), "BatchMode=yes".to_string()]);
    }
    if config.connect_timeout > 0 {
        args.extend([
            "-o".to_string(),
            format!("ConnectTimeout={}", config.connect_timeout),
        ]);
    }
    for option in &config.ssh_options {
        args.extend(["-o".to_string(), option.clone()]);
    }
    args.push(config.host.clone());
    args
}

fn run_remote(config: &Config, command: &str, batch: bool) -> ZtResult<Output> {
    let remote = remote_cmd(config, command);
    let argv = ssh_argv(config, batch, false);
    Command::new(&argv[0])
        .args(&argv[1..])
        .arg(remote)
        .output()
        .map_err(|error| ZtError::new(format!("ssh failed: {error}"), 1))
}

fn remote_error(output: &Output, action: &str) -> ZtError {
    let detail = output_text(output);
    ZtError::new(
        format!(
            "{action} failed on remote host: {}",
            if detail.trim().is_empty() {
                format!("exit {}", output.status.code().unwrap_or(1))
            } else {
                detail.trim().to_string()
            }
        ),
        output.status.code().unwrap_or(1),
    )
}

fn output_text(output: &Output) -> String {
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    [stdout.trim(), stderr.trim()]
        .into_iter()
        .filter(|part| !part.is_empty())
        .collect::<Vec<_>>()
        .join("\n")
}

fn output_stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).trim().to_string()
}

fn output_stderr(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).trim().to_string()
}

fn print_json(value: &serde_json::Value) -> ZtResult<()> {
    println!(
        "{}",
        serde_json::to_string(value).map_err(|error| ZtError::new(error.to_string(), 1))?
    );
    Ok(())
}

fn shell_quote(value: &str) -> String {
    if value.is_empty() {
        return "''".to_string();
    }
    if value
        .bytes()
        .all(|byte| byte.is_ascii_alphanumeric() || b"@%_+=:,./-".contains(&byte))
    {
        return value.to_string();
    }
    format!("'{}'", value.replace('\'', "'\"'\"'"))
}

fn print_command(argv: &[String]) {
    println!(
        "{}",
        argv.iter()
            .map(|part| shell_quote(part))
            .collect::<Vec<_>>()
            .join(" ")
    );
}

fn command_status(argv: &[String]) -> ZtResult<i32> {
    let status = Command::new(&argv[0]).args(&argv[1..]).status()?;
    Ok(status.code().unwrap_or(1))
}

fn command_output(argv: &[String]) -> ZtResult<Output> {
    Command::new(&argv[0])
        .args(&argv[1..])
        .output()
        .map_err(ZtError::from)
}

fn slugify(value: &str) -> String {
    let mut slug = String::new();
    let mut last_dash = false;
    for character in value.chars().flat_map(|character| character.to_lowercase()) {
        if character.is_ascii_alphanumeric() {
            slug.push(character);
            last_dash = false;
        } else if !last_dash && !slug.is_empty() {
            slug.push('-');
            last_dash = true;
        }
    }
    while slug.ends_with('-') {
        slug.pop();
    }
    if slug.is_empty() {
        "zt".to_string()
    } else {
        slug
    }
}

fn auto_session_name(scope: &str, host: Option<&str>) -> String {
    let base = if scope == "local" {
        "mb"
    } else {
        host.unwrap_or("remote")
    };
    let random = random_suffix();
    format!("{}-{}-{random}", slugify(base), utc_timestamp())
}

fn utc_timestamp() -> String {
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default();
    let seconds = now.as_secs() as i64;
    let days = seconds.div_euclid(86_400);
    let second_of_day = seconds.rem_euclid(86_400);
    let (year, month, day) = civil_from_days(days);
    let hour = second_of_day / 3_600;
    let minute = (second_of_day % 3_600) / 60;
    let second = second_of_day % 60;
    format!("{year:04}{month:02}{day:02}-{hour:02}{minute:02}{second:02}")
}

fn civil_from_days(days_since_unix_epoch: i64) -> (i64, i64, i64) {
    let z = days_since_unix_epoch + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 }.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096).div_euclid(365);
    let year = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2).div_euclid(153);
    let day = doy - (153 * mp + 2).div_euclid(5) + 1;
    let month = mp + if mp < 10 { 3 } else { -9 };
    let year = year + if month <= 2 { 1 } else { 0 };
    (year, month, day)
}

fn random_suffix() -> String {
    let mut bytes = [0_u8; 3];
    if fs::File::open("/dev/urandom")
        .and_then(|mut file| file.read_exact(&mut bytes))
        .is_ok()
    {
        return bytes
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect::<String>();
    }

    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|duration| duration.as_nanos())
        .unwrap_or_default();
    let value = (nanos ^ std::process::id() as u128) & 0xffffff;
    format!("{value:06x}")
}

fn resolve_session_name(session: &str, auto: bool, scope: &str, host: Option<&str>) -> String {
    if auto || matches!(session, "" | "-" | "auto" | "new") {
        auto_session_name(scope, host)
    } else {
        session.to_string()
    }
}

fn list_sessions(config: &Config, reverse: bool) -> ZtResult<Vec<String>> {
    let mut command = "zellij list-sessions --short --no-formatting".to_string();
    if reverse {
        command.push_str(" --reverse");
    }
    let output = run_remote(config, &command, true)?;
    let combined = output_text(&output);
    if combined.contains("No active zellij sessions found") {
        return Ok(Vec::new());
    }
    if !output.status.success() {
        return Err(remote_error(&output, "list sessions"));
    }
    Ok(combined
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.contains("No active zellij sessions found"))
        .map(ToString::to_string)
        .collect())
}

fn filter_sessions(
    sessions: Vec<String>,
    prefix: Option<&str>,
    contains: Option<&str>,
) -> Vec<String> {
    sessions
        .into_iter()
        .filter(|session| prefix.is_none_or(|prefix| session.starts_with(prefix)))
        .filter(|session| contains.is_none_or(|contains| session.contains(contains)))
        .collect()
}

fn session_exists(config: &Config, session: &str) -> ZtResult<bool> {
    Ok(list_sessions(config, false)?
        .iter()
        .any(|item| item == session))
}

fn ensure_session(
    config: &Config,
    session: &str,
    json_output: bool,
    print_only: bool,
) -> ZtResult<i32> {
    let command = remote_cmd(
        config,
        &format!("zellij attach --create-background {}", shell_quote(session)),
    );
    let mut argv = ssh_argv(config, true, false);
    argv.push(command);

    if print_only {
        print_command(&argv);
        return Ok(0);
    }

    let output = command_output(&argv)?;
    if json_output {
        print_json(&json!({
            "host": config.host,
            "session": session,
            "ensured": output.status.success(),
            "stdout": output_stdout(&output),
            "stderr": output_stderr(&output),
        }))?;
    } else {
        io::stdout().write_all(&output.stdout)?;
        if output.status.success() && output.stdout.is_empty() {
            println!("{session}");
        }
        if !output.status.success() {
            io::stderr().write_all(&output.stderr)?;
        }
    }
    Ok(output.status.code().unwrap_or(1))
}

fn attach(
    config: &Config,
    session: &str,
    create: bool,
    background: bool,
    json_output: bool,
    print_only: bool,
) -> ZtResult<i32> {
    if background {
        return ensure_session(config, session, json_output, print_only);
    }

    let flags = if create { " --create" } else { "" };
    let command = remote_cmd(
        config,
        &format!("exec zellij attach{flags} {}", shell_quote(session)),
    );
    let argv = if config.transport == Transport::Mosh {
        vec![
            "mosh".to_string(),
            config.host.clone(),
            "--".to_string(),
            "sh".to_string(),
            "-lc".to_string(),
            command,
        ]
    } else {
        let mut args = ssh_argv(config, false, true);
        args.push(command);
        args
    };

    if print_only {
        print_command(&argv);
        return Ok(0);
    }
    if json_output {
        print_json(&json!({
            "host": config.host,
            "session": session,
            "attached": false,
            "command": argv.iter().map(|part| shell_quote(part)).collect::<Vec<_>>().join(" "),
        }))?;
        return Ok(0);
    }
    command_status(&argv)
}

fn attach_local(
    session: &str,
    create: bool,
    background: bool,
    json_output: bool,
    print_only: bool,
) -> ZtResult<i32> {
    let zellij = which::which("zellij").map_err(|_| {
        ZtError::new(
            "local zellij not found; run 'zt install --with-local-zellij'",
            127,
        )
    })?;
    let mut argv = vec![zellij.display().to_string(), "attach".to_string()];
    if background {
        argv.push("--create-background".to_string());
    } else if create {
        argv.push("--create".to_string());
    }
    argv.push(session.to_string());

    if print_only {
        print_command(&argv);
        return Ok(0);
    }
    if json_output {
        print_json(&json!({
            "scope": "local",
            "session": session,
            "attached": false,
            "command": argv.iter().map(|part| shell_quote(part)).collect::<Vec<_>>().join(" "),
        }))?;
        return Ok(0);
    }
    command_status(&argv)
}

fn is_missing_session_output(output: &str) -> bool {
    output.contains("No session named") || output.contains("not found")
}

fn kill_session(
    config: &Config,
    session: &str,
    missing_ok: bool,
    json_output: bool,
) -> ZtResult<i32> {
    if missing_ok && !session_exists(config, session)? {
        if json_output {
            print_json(
                &json!({"host": config.host, "session": session, "closed": false, "missing": true}),
            )?;
        }
        return Ok(0);
    }

    let output = run_remote(
        config,
        &format!("zellij kill-session {}", shell_quote(session)),
        true,
    )?;
    let missing = !output.status.success() && is_missing_session_output(&output_text(&output));
    if missing_ok && missing {
        if json_output {
            print_json(
                &json!({"host": config.host, "session": session, "closed": false, "missing": true}),
            )?;
        }
        return Ok(0);
    }

    if json_output {
        print_json(&json!({
            "host": config.host,
            "session": session,
            "closed": output.status.success(),
            "missing": missing,
            "stdout": output_stdout(&output),
            "stderr": output_stderr(&output),
        }))?;
    } else {
        io::stdout().write_all(&output.stdout)?;
        if !output.status.success() {
            io::stderr().write_all(&output.stderr)?;
        }
    }
    Ok(output.status.code().unwrap_or(1))
}

fn delete_session(
    config: &Config,
    session: &str,
    force: bool,
    missing_ok: bool,
    json_output: bool,
) -> ZtResult<i32> {
    let force_flag = if force { " --force" } else { "" };
    let output = run_remote(
        config,
        &format!("zellij delete-session{force_flag} {}", shell_quote(session)),
        true,
    )?;
    let missing = !output.status.success() && is_missing_session_output(&output_text(&output));
    if missing_ok && missing {
        if json_output {
            print_json(
                &json!({"host": config.host, "session": session, "deleted": false, "missing": true}),
            )?;
        }
        return Ok(0);
    }

    if json_output {
        print_json(&json!({
            "host": config.host,
            "session": session,
            "deleted": output.status.success(),
            "missing": missing,
            "force": force,
            "stdout": output_stdout(&output),
            "stderr": output_stderr(&output),
        }))?;
    } else {
        io::stdout().write_all(&output.stdout)?;
        if !output.status.success() {
            io::stderr().write_all(&output.stderr)?;
        }
    }
    Ok(output.status.code().unwrap_or(1))
}

fn choose_with_fzf(items: &[String]) -> Option<String> {
    if !io::stdin().is_terminal() || !io::stdout().is_terminal() || which::which("fzf").is_err() {
        return None;
    }
    let mut child = Command::new("fzf")
        .args(["--prompt", "zellij> ", "--height", "40%", "--reverse"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .ok()?;
    if let Some(stdin) = child.stdin.as_mut() {
        let _ = writeln!(stdin, "{}", items.join("\n"));
    }
    let output = child.wait_with_output().ok()?;
    if !output.status.success() {
        return Some(String::new());
    }
    Some(String::from_utf8_lossy(&output.stdout).trim().to_string())
}

fn prompt_choice(sessions: &[String]) -> ZtResult<String> {
    if sessions.is_empty() {
        return prompt_new_name();
    }
    for (index, session) in sessions.iter().enumerate() {
        println!("{:2}. {}", index + 1, session);
    }
    println!("{:2}. {NEW_MARKER}", sessions.len() + 1);

    print!("session> ");
    io::stdout().flush()?;
    let mut answer = String::new();
    io::stdin().read_line(&mut answer)?;
    let answer = answer.trim();
    if answer.is_empty() {
        return Ok(String::new());
    }
    if let Ok(choice) = answer.parse::<usize>() {
        if (1..=sessions.len()).contains(&choice) {
            return Ok(sessions[choice - 1].clone());
        }
        if choice == sessions.len() + 1 {
            return prompt_new_name();
        }
    }
    Ok(answer.to_string())
}

fn prompt_new_name() -> ZtResult<String> {
    print!("new session name [main]> ");
    io::stdout().flush()?;
    let mut name = String::new();
    io::stdin().read_line(&mut name)?;
    let name = name.trim();
    Ok(if name.is_empty() {
        "main".to_string()
    } else {
        name.to_string()
    })
}

fn browse(config: &Config) -> ZtResult<i32> {
    if config.no_input || !io::stdin().is_terminal() || !io::stdout().is_terminal() {
        return Err(ZtError::new(
            "browse requires an interactive terminal; use 'zt list', 'zt ensure SESSION', or 'zt attach SESSION'",
            2,
        ));
    }
    if config.picker == Picker::None {
        return Err(ZtError::new(
            "browse is disabled because picker is set to none",
            2,
        ));
    }

    let sessions = list_sessions(config, false)?;
    let mut choices = vec![NEW_MARKER.to_string()];
    choices.extend(sessions.iter().cloned());
    let mut choice = if matches!(config.picker, Picker::Auto | Picker::Fzf) {
        choose_with_fzf(&choices)
    } else {
        None
    };
    if choice.is_none() && config.picker == Picker::Fzf {
        return Err(ZtError::new(
            "picker is set to fzf, but fzf is unavailable or not attached to a terminal",
            2,
        ));
    }
    if choice.is_none() {
        choice = Some(prompt_choice(&sessions)?);
    }
    let mut choice = choice.unwrap_or_default();
    if choice.is_empty() {
        return Ok(130);
    }
    if choice == NEW_MARKER {
        choice = prompt_new_name()?;
    }
    attach(config, &choice, true, false, false, false)
}

fn local_tool_status(tool: &str) -> ToolStatus {
    let Ok(path) = which::which(tool) else {
        return ToolStatus {
            present: false,
            path: None,
            version: None,
        };
    };
    let version_args = match tool {
        "ssh" | "tmux" => vec![tool.to_string(), "-V".to_string()],
        _ => vec![tool.to_string(), "--version".to_string()],
    };
    let version = command_output(&version_args).ok().and_then(|output| {
        let text = output_text(&output);
        text.lines().next().map(ToString::to_string)
    });
    ToolStatus {
        present: true,
        path: Some(path.display().to_string()),
        version,
    }
}

fn remote_tool_status(config: &Config) -> ZtResult<(serde_json::Value, Option<String>)> {
    let script = r#"
printf 'hostname\t%s\n' "$(hostname 2>/dev/null || uname -n)"
for tool in zellij tmux mosh; do
  tool_path=$(command -v "$tool" 2>/dev/null || true)
  if [ -z "$tool_path" ]; then
    printf 'tool\t%s\t\t\n' "$tool"
    continue
  fi
  case "$tool" in
    tmux) version=$("$tool" -V 2>&1 | sed -n '1p') ;;
    *) version=$("$tool" --version 2>&1 | sed -n '1p') ;;
  esac
  printf 'tool\t%s\t%s\t%s\n' "$tool" "$tool_path" "$version"
done
"#;
    let output = run_remote(config, script, true)?;
    let mut hostname = serde_json::Value::Null;
    let mut tools = serde_json::Map::new();
    if !output.status.success() {
        return Ok((
            json!({"hostname": null, "tools": {}}),
            Some(output_text(&output)),
        ));
    }

    for line in String::from_utf8_lossy(&output.stdout).lines() {
        let parts = line.split('\t').collect::<Vec<_>>();
        if parts.is_empty() {
            continue;
        }
        if parts[0] == "hostname" && parts.len() >= 2 {
            hostname = json!(parts[1]);
        } else if parts[0] == "tool" && parts.len() >= 4 {
            tools.insert(
                parts[1].to_string(),
                json!({
                    "present": !parts[2].is_empty(),
                    "path": if parts[2].is_empty() { serde_json::Value::Null } else { json!(parts[2]) },
                    "version": if parts[3].is_empty() { serde_json::Value::Null } else { json!(parts[3]) },
                }),
            );
        }
    }
    Ok((json!({"hostname": hostname, "tools": tools}), None))
}

fn status(config: &Config, json_output: bool) -> ZtResult<i32> {
    let local = ["ssh", "mosh", "zellij", "fzf"]
        .into_iter()
        .map(|tool| (tool.to_string(), local_tool_status(tool)))
        .collect::<BTreeMap<_, _>>();
    let (remote, remote_error_message) = remote_tool_status(config)?;
    let remote_tools = remote
        .get("tools")
        .and_then(|tools| tools.as_object())
        .cloned()
        .unwrap_or_default();
    let remote_zellij = remote_tools
        .get("zellij")
        .and_then(|tool| tool.get("present"))
        .and_then(|present| present.as_bool())
        .unwrap_or(false);
    let remote_mosh = remote_tools
        .get("mosh")
        .and_then(|tool| tool.get("present"))
        .and_then(|present| present.as_bool())
        .unwrap_or(false);
    let local_ssh = local.get("ssh").is_some_and(|tool| tool.present);
    let local_mosh = local.get("mosh").is_some_and(|tool| tool.present);
    let ok = local_ssh
        && remote_zellij
        && (config.transport != Transport::Mosh || (local_mosh && remote_mosh))
        && remote_error_message.is_none();

    let data = json!({
        "ok": ok,
        "host": config.host,
        "transport": config.transport.as_str(),
        "picker": config.picker.as_str(),
        "connect_timeout": config.connect_timeout,
        "config_path": config.config_path.display().to_string(),
        "config_loaded": config.config_loaded,
        "local": local,
        "remote": remote,
        "remote_error": remote_error_message,
    });

    if json_output {
        print_json(&data)?;
    } else {
        println!("host: {}", config.host);
        println!("transport: {}", config.transport.as_str());
        println!("picker: {}", config.picker.as_str());
        println!(
            "config: {} ({})",
            config.config_path.display(),
            if config.config_loaded {
                "loaded"
            } else {
                "missing"
            }
        );
        if let Some(hostname) = data
            .get("remote")
            .and_then(|remote| remote.get("hostname"))
            .and_then(|hostname| hostname.as_str())
        {
            println!("remote hostname: {hostname}");
        }
        if let Some(message) = data.get("remote_error").and_then(|value| value.as_str()) {
            eprintln!("remote error: {message}");
        }
        println!("local:");
        for (tool, info) in &local {
            if info.present {
                println!(
                    "  {tool}: {} ({})",
                    info.path.as_deref().unwrap_or(""),
                    info.version.as_deref().unwrap_or("")
                );
            } else {
                println!("  {tool}: missing");
            }
        }
        println!("remote:");
        for (tool, info) in &remote_tools {
            let present = info
                .get("present")
                .and_then(|value| value.as_bool())
                .unwrap_or(false);
            if present {
                println!(
                    "  {tool}: {} ({})",
                    info.get("path")
                        .and_then(|value| value.as_str())
                        .unwrap_or(""),
                    info.get("version")
                        .and_then(|value| value.as_str())
                        .unwrap_or("")
                );
            } else {
                println!("  {tool}: missing");
            }
        }
    }
    Ok(if ok { 0 } else { 1 })
}

fn detect_local_package_manager() -> Option<String> {
    for manager in package_managers() {
        if which::which(manager).is_ok() {
            return Some(manager.to_string());
        }
    }
    None
}

fn detect_remote_package_manager(config: &Config) -> ZtResult<Option<String>> {
    let managers = package_managers()
        .iter()
        .map(|manager| shell_quote(manager))
        .collect::<Vec<_>>()
        .join(" ");
    let command = format!(
        "for manager in {managers}; do command -v \"$manager\" >/dev/null 2>&1 && printf \"%s\\n\" \"$manager\" && exit 0; done; exit 1"
    );
    let output = run_remote(config, &command, true)?;
    if !output.status.success() {
        return Ok(None);
    }
    Ok(String::from_utf8_lossy(&output.stdout)
        .lines()
        .next()
        .map(|line| line.trim().to_string())
        .filter(|line| !line.is_empty()))
}

fn package_managers() -> [&'static str; 5] {
    ["brew", "apt-get", "dnf", "pacman", "apk"]
}

fn local_missing_tools(tools: &[String]) -> Vec<String> {
    tools
        .iter()
        .filter(|tool| which::which(tool).is_err())
        .cloned()
        .collect()
}

fn remote_missing_tools(config: &Config, tools: &[String]) -> ZtResult<Vec<String>> {
    if tools.is_empty() {
        return Ok(Vec::new());
    }
    let tool_args = tools
        .iter()
        .map(|tool| shell_quote(tool))
        .collect::<Vec<_>>()
        .join(" ");
    let command = format!(
        "for tool in {tool_args}; do command -v \"$tool\" >/dev/null 2>&1 || printf \"%s\\n\" \"$tool\"; done"
    );
    let output = run_remote(config, &command, true)?;
    if !output.status.success() {
        return Err(remote_error(&output, "check remote dependencies"));
    }
    Ok(String::from_utf8_lossy(&output.stdout)
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .map(ToString::to_string)
        .collect())
}

fn package_install_command(package_manager: &str, packages: &[String]) -> ZtResult<String> {
    let package_args = packages
        .iter()
        .map(|package| shell_quote(package))
        .collect::<Vec<_>>()
        .join(" ");
    match package_manager {
        "brew" => Ok(format!("brew install {package_args}")),
        "apt-get" => Ok(format!(
            "sudo apt-get update && sudo apt-get install -y {package_args}"
        )),
        "dnf" => Ok(format!("sudo dnf install -y {package_args}")),
        "pacman" => Ok(format!(
            "sudo pacman -S --needed --noconfirm {package_args}"
        )),
        "apk" => Ok(format!("sudo apk add {package_args}")),
        _ => Err(ZtError::new(
            format!("unsupported package manager: {package_manager}"),
            2,
        )),
    }
}

fn install_tool_targets(config: &Config, args: &InstallArgs) -> (Vec<String>, Vec<String>) {
    let mut local = BTreeSet::new();
    let mut remote = BTreeSet::from(["zellij".to_string()]);

    if !args.no_fzf && matches!(config.picker, Picker::Auto | Picker::Fzf) {
        local.insert("fzf".to_string());
    }
    if args.with_mosh || config.transport == Transport::Mosh {
        local.insert("mosh".to_string());
        remote.insert("mosh".to_string());
    }
    if args.with_tmux {
        remote.insert("tmux".to_string());
    }
    if args.with_local_zellij {
        local.insert("zellij".to_string());
    }

    (local.into_iter().collect(), remote.into_iter().collect())
}

fn install_scopes(args: &InstallArgs) -> Vec<String> {
    if args.local_only {
        vec!["local".to_string()]
    } else if args.remote_only {
        vec!["remote".to_string()]
    } else {
        vec!["local".to_string(), "remote".to_string()]
    }
}

fn build_install_plan(config: &Config, args: &InstallArgs) -> ZtResult<InstallPlan> {
    let scopes = install_scopes(args);
    let (local_targets, remote_targets) = install_tool_targets(config, args);
    let mut plan = Vec::new();
    let mut installed = BTreeMap::from([
        ("local".to_string(), Vec::new()),
        ("remote".to_string(), Vec::new()),
    ]);
    let mut missing = installed.clone();
    let mut package_managers =
        BTreeMap::from([("local".to_string(), None), ("remote".to_string(), None)]);
    let targets = BTreeMap::from([
        ("local".to_string(), local_targets.clone()),
        ("remote".to_string(), remote_targets.clone()),
    ]);

    if scopes.iter().any(|scope| scope == "local") && !local_targets.is_empty() {
        let local_missing = local_missing_tools(&local_targets);
        let local_installed = local_targets
            .iter()
            .filter(|tool| !local_missing.contains(tool))
            .cloned()
            .collect::<Vec<_>>();
        installed.insert("local".to_string(), local_installed);
        missing.insert("local".to_string(), local_missing.clone());
        if !local_missing.is_empty() {
            let manager = detect_local_package_manager().ok_or_else(|| {
                ZtError::new(
                    "no supported local package manager found (expected brew, apt-get, dnf, pacman, or apk)",
                    2,
                )
            })?;
            package_managers.insert("local".to_string(), Some(manager.clone()));
            plan.push(InstallEntry {
                scope: "local".to_string(),
                package_manager: manager.clone(),
                packages: local_missing.clone(),
                command: package_install_command(&manager, &local_missing)?,
            });
        }
    }

    if scopes.iter().any(|scope| scope == "remote") && !remote_targets.is_empty() {
        let remote_missing = remote_missing_tools(config, &remote_targets)?;
        let remote_installed = remote_targets
            .iter()
            .filter(|tool| !remote_missing.contains(tool))
            .cloned()
            .collect::<Vec<_>>();
        installed.insert("remote".to_string(), remote_installed);
        missing.insert("remote".to_string(), remote_missing.clone());
        if !remote_missing.is_empty() {
            let manager = detect_remote_package_manager(config)?.ok_or_else(|| {
                ZtError::new(
                    format!(
                        "no supported package manager found on {} (expected brew, apt-get, dnf, pacman, or apk)",
                        config.host
                    ),
                    2,
                )
            })?;
            package_managers.insert("remote".to_string(), Some(manager.clone()));
            plan.push(InstallEntry {
                scope: "remote".to_string(),
                package_manager: manager.clone(),
                packages: remote_missing.clone(),
                command: package_install_command(&manager, &remote_missing)?,
            });
        }
    }

    Ok(InstallPlan {
        host: config.host.clone(),
        transport: config.transport.as_str().to_string(),
        picker: config.picker.as_str().to_string(),
        scopes,
        targets,
        installed,
        missing,
        package_managers,
        plan,
    })
}

fn confirm_install(plan: &[InstallEntry], yes: bool, no_input: bool) -> ZtResult<()> {
    if plan.is_empty() || yes {
        return Ok(());
    }
    if no_input || !io::stdin().is_terminal() {
        return Err(ZtError::new(
            "install requires --yes in noninteractive mode",
            2,
        ));
    }
    println!("zt will run:");
    for entry in plan {
        println!("  [{}] {}", entry.scope, entry.command);
    }
    print!("install missing dependencies? [y/N] ");
    io::stdout().flush()?;
    let mut answer = String::new();
    io::stdin().read_line(&mut answer)?;
    if !matches!(answer.trim().to_ascii_lowercase().as_str(), "y" | "yes") {
        return Err(ZtError::new("install cancelled", 130));
    }
    Ok(())
}

fn run_install_entry(
    config: &Config,
    entry: &InstallEntry,
    json_output: bool,
) -> ZtResult<serde_json::Value> {
    if entry.scope == "local" {
        if json_output {
            let output = Command::new("sh")
                .arg("-lc")
                .arg(&entry.command)
                .output()
                .map_err(ZtError::from)?;
            return Ok(json!({
                "scope": entry.scope,
                "command": entry.command,
                "returncode": output.status.code().unwrap_or(1),
                "stdout": output_stdout(&output),
                "stderr": output_stderr(&output),
            }));
        }
        let status = Command::new("sh")
            .arg("-lc")
            .arg(&entry.command)
            .status()
            .map_err(ZtError::from)?;
        return Ok(json!({
            "scope": entry.scope,
            "command": entry.command,
            "returncode": status.code().unwrap_or(1),
        }));
    }

    let mut argv = ssh_argv(config, json_output, !json_output);
    argv.push(remote_cmd(config, &entry.command));
    if json_output {
        let output = command_output(&argv)?;
        return Ok(json!({
            "scope": entry.scope,
            "command": argv.iter().map(|part| shell_quote(part)).collect::<Vec<_>>().join(" "),
            "returncode": output.status.code().unwrap_or(1),
            "stdout": output_stdout(&output),
            "stderr": output_stderr(&output),
        }));
    }
    let returncode = command_status(&argv)?;
    Ok(json!({
        "scope": entry.scope,
        "command": argv.iter().map(|part| shell_quote(part)).collect::<Vec<_>>().join(" "),
        "returncode": returncode,
    }))
}

fn install_dependencies(config: &Config, args: &InstallArgs) -> ZtResult<i32> {
    let plan = build_install_plan(config, args)?;
    if args.dry_run {
        if args.json {
            let mut data =
                serde_json::to_value(&plan).map_err(|error| ZtError::new(error.to_string(), 1))?;
            data["dry_run"] = json!(true);
            print_json(&data)?;
        } else if plan.plan.is_empty() {
            println!("all selected dependencies are already installed");
        } else {
            for entry in &plan.plan {
                println!("[{}] {}", entry.scope, entry.command);
            }
        }
        return Ok(0);
    }

    confirm_install(&plan.plan, args.yes, config.no_input)?;
    let mut results = Vec::new();
    let mut failed = false;
    for entry in &plan.plan {
        let result = run_install_entry(config, entry, args.json)?;
        let returncode = result
            .get("returncode")
            .and_then(|value| value.as_i64())
            .unwrap_or(1);
        failed |= returncode != 0;
        results.push(result);
    }

    if args.json {
        let mut data =
            serde_json::to_value(&plan).map_err(|error| ZtError::new(error.to_string(), 1))?;
        data["dry_run"] = json!(false);
        data["results"] = json!(results);
        data["ok"] = json!(!failed);
        print_json(&data)?;
    } else if plan.plan.is_empty() {
        println!("all selected dependencies are already installed");
    } else if failed {
        eprintln!("one or more install commands failed");
    }
    Ok(if failed { 1 } else { 0 })
}


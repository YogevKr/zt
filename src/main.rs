fn main() {
    let args = normalize_shortcut(env::args().skip(1).collect());
    let cli = Cli::parse_from(std::iter::once("zt".to_string()).chain(args));

    match run(cli) {
        Ok(code) => std::process::exit(code),
        Err(error) => {
            eprintln!("zt: {}", error.message);
            std::process::exit(error.code);
        }
    }
}

fn run(cli: Cli) -> ZtResult<i32> {
    let config = build_config(&cli)?;

    match &cli.command {
        Some(Commands::Browse) => browse(&config),
        Some(Commands::Config(args)) => config_command(&config, args),
        Some(Commands::Install(args)) => install_dependencies(&config, args),
        Some(Commands::Local(args)) => {
            let session =
                resolve_session_name(&args.session, args.auto, "local", Some(&config.host));
            attach_local(
                &session,
                !args.no_create,
                args.background,
                args.json,
                args.print_command,
            )
        }
        Some(Commands::Remote(args)) => {
            let session =
                resolve_session_name(&args.session, args.auto, "remote", Some(&config.host));
            attach(
                &config,
                &session,
                !args.no_create,
                args.background,
                args.json,
                args.print_command,
            )
        }
        Some(Commands::List(args)) => {
            let sessions = filter_sessions(
                list_sessions(&config, args.reverse)?,
                args.prefix.as_deref(),
                args.contains.as_deref(),
            );
            if args.json {
                print_json(
                    &json!({"host": config.host, "sessions": sessions, "count": sessions.len()}),
                )?;
            } else if args.count {
                println!("{}", sessions.len());
            } else {
                for session in sessions {
                    println!("{session}");
                }
            }
            Ok(0)
        }
        Some(Commands::Status(args)) => status(&config, args.json),
        Some(Commands::Exists(args)) => {
            let exists = session_exists(&config, &args.session)?;
            if args.json {
                print_json(
                    &json!({"host": config.host, "session": args.session, "exists": exists}),
                )?;
            }
            Ok(if exists { 0 } else { 1 })
        }
        Some(Commands::Ensure(args)) => {
            ensure_session(&config, &args.session, args.json, args.print_command)
        }
        Some(Commands::Attach(args)) => {
            let session =
                resolve_session_name(&args.session, args.auto, "remote", Some(&config.host));
            attach(
                &config,
                &session,
                !args.no_create,
                args.background,
                args.json,
                args.print_command,
            )
        }
        Some(Commands::New(args)) => {
            let session =
                resolve_session_name(&args.session, args.auto, "remote", Some(&config.host));
            attach(
                &config,
                &session,
                true,
                args.background,
                args.json,
                args.print_command,
            )
        }
        Some(Commands::Kill(args)) => {
            kill_session(&config, &args.session, args.missing_ok, args.json)
        }
        Some(Commands::Delete(args)) => delete_session(
            &config,
            &args.session,
            !args.no_force,
            args.missing_ok,
            args.json,
        ),
        None => {
            if config.no_input || !io::stdin().is_terminal() || !io::stdout().is_terminal() {
                Err(ZtError::new(
                    "no command provided; use 'zt --help' for noninteractive commands",
                    2,
                ))
            } else {
                browse(&config)
            }
        }
    }
}

fn normalize_shortcut(argv: Vec<String>) -> Vec<String> {
    let options_with_values = [
        "-H",
        "--host",
        "--config",
        "--remote-path",
        "--connect-timeout",
        "--ssh-option",
        "--picker",
    ];
    let flags = ["--ssh", "--mosh", "--no-input", "-h", "--help", "--version"];
    let mut skip_next = false;

    for (index, arg) in argv.iter().enumerate() {
        if skip_next {
            skip_next = false;
            continue;
        }
        if arg == "--" {
            break;
        }
        if options_with_values.contains(&arg.as_str()) {
            skip_next = true;
            continue;
        }
        if options_with_values
            .iter()
            .any(|option| arg.starts_with(&format!("{option}=")))
        {
            continue;
        }
        if flags.contains(&arg.as_str()) || arg.starts_with('-') {
            continue;
        }
        if !KNOWN_COMMANDS.contains(&arg.as_str()) {
            let mut normalized = Vec::with_capacity(argv.len() + 1);
            normalized.extend_from_slice(&argv[..index]);
            normalized.push("attach".to_string());
            normalized.push(arg.clone());
            normalized.extend_from_slice(&argv[index + 1..]);
            return normalized;
        }
        return argv;
    }
    argv
}

fn build_config(cli: &Cli) -> ZtResult<Config> {
    let mut config = Config::defaults();
    if let Some(path) = &cli.config {
        config.config_path = expand_tilde(path);
    }

    let file_values = read_config_file(&config.config_path)?;
    config.config_loaded = !file_values.is_empty();
    apply_values(&mut config, &file_values)?;
    apply_values(&mut config, &env_config_values()?)?;

    if let Some(host) = &cli.host {
        apply_host(&mut config, host)?;
    }
    if let Some(remote_path) = &cli.remote_path {
        apply_remote_path(&mut config, remote_path)?;
    }
    if let Some(connect_timeout) = cli.connect_timeout {
        config.connect_timeout = connect_timeout;
    }
    if !cli.ssh_options.is_empty() {
        config.ssh_options = cli.ssh_options.clone();
    }
    if let Some(picker) = cli.picker {
        config.picker = picker.picker();
    }
    if cli.no_input {
        config.no_input = true;
    }
    if cli.mosh {
        config.transport = Transport::Mosh;
    } else if cli.ssh {
        config.transport = Transport::Ssh;
    }

    Ok(config)
}

fn default_config_path() -> PathBuf {
    env::var(CONFIG_ENV)
        .map(|value| expand_tilde(&value))
        .unwrap_or_else(|_| expand_tilde(DEFAULT_CONFIG_PATH))
}

fn expand_tilde(path: &str) -> PathBuf {
    if path == "~" {
        return env::var_os("HOME")
            .map(PathBuf::from)
            .unwrap_or_else(|| PathBuf::from(path));
    }
    if let Some(rest) = path.strip_prefix("~/")
        && let Some(home) = env::var_os("HOME")
    {
        return PathBuf::from(home).join(rest);
    }
    PathBuf::from(path)
}

fn read_config_file(path: &PathBuf) -> ZtResult<BTreeMap<String, TomlValue>> {
    if !path.exists() {
        return Ok(BTreeMap::new());
    }
    let content = fs::read_to_string(path).map_err(|error| {
        ZtError::new(
            format!("could not read config file {}: {error}", path.display()),
            2,
        )
    })?;
    let raw: TomlValue = toml::from_str(&content).map_err(|error| {
        ZtError::new(
            format!("could not parse config file {}: {error}", path.display()),
            2,
        )
    })?;
    let table = if let Some(defaults) = raw.get("defaults") {
        defaults
            .as_table()
            .ok_or_else(|| ZtError::new("config [defaults] must be a table", 2))?
    } else {
        raw.as_table()
            .ok_or_else(|| ZtError::new("config must be a table", 2))?
    };
    Ok(table
        .iter()
        .map(|(key, value)| (key.clone(), value.clone()))
        .collect())
}

fn env_config_values() -> ZtResult<BTreeMap<String, TomlValue>> {
    let mut values = BTreeMap::new();
    for (env_name, key) in [
        ("ZT_HOST", "host"),
        ("ZT_TRANSPORT", "transport"),
        ("ZT_PICKER", "picker"),
        ("ZT_REMOTE_PATH", "remote_path"),
        ("ZT_CONNECT_TIMEOUT", "connect_timeout"),
        ("ZT_SSH_OPTIONS", "ssh_options"),
        ("ZT_NO_INPUT", "no_input"),
    ] {
        if let Ok(value) = env::var(env_name) {
            values.insert(key.to_string(), TomlValue::String(value));
        }
    }
    Ok(values)
}

fn apply_values(config: &mut Config, values: &BTreeMap<String, TomlValue>) -> ZtResult<()> {
    for (key, value) in values {
        match key.as_str() {
            "host" => apply_host(config, value_as_str(value, key)?)?,
            "transport" => config.transport = Transport::parse(value_as_str(value, key)?)?,
            "picker" => config.picker = Picker::parse(value_as_str(value, key)?)?,
            "remote_path" => apply_remote_path(config, value_as_str(value, key)?)?,
            "connect_timeout" => config.connect_timeout = value_as_u64(value, key)?,
            "ssh_options" => config.ssh_options = value_as_string_list(value, key)?,
            "no_input" => config.no_input = value_as_bool(value, key)?,
            _ => return Err(ZtError::new(format!("unknown config key: {key}"), 2)),
        }
    }
    Ok(())
}

fn apply_host(config: &mut Config, value: &str) -> ZtResult<()> {
    if value.is_empty() {
        return Err(ZtError::new("host must be a non-empty string", 2));
    }
    config.host = value.to_string();
    Ok(())
}

fn apply_remote_path(config: &mut Config, value: &str) -> ZtResult<()> {
    if value.is_empty() {
        return Err(ZtError::new("remote_path must be a non-empty string", 2));
    }
    config.remote_path = value.to_string();
    Ok(())
}

fn value_as_str<'a>(value: &'a TomlValue, key: &str) -> ZtResult<&'a str> {
    value
        .as_str()
        .ok_or_else(|| ZtError::new(format!("{key} must be a string"), 2))
}

fn value_as_u64(value: &TomlValue, key: &str) -> ZtResult<u64> {
    if let Some(integer) = value.as_integer()
        && integer >= 0
    {
        return Ok(integer as u64);
    }
    if let Some(text) = value.as_str() {
        return text
            .parse::<u64>()
            .map_err(|_| ZtError::new(format!("{key} must be an integer"), 2));
    }
    Err(ZtError::new(format!("{key} must be an integer"), 2))
}

fn value_as_bool(value: &TomlValue, key: &str) -> ZtResult<bool> {
    if let Some(boolean) = value.as_bool() {
        return Ok(boolean);
    }
    if let Some(text) = value.as_str() {
        return match text.trim().to_ascii_lowercase().as_str() {
            "1" | "true" | "yes" | "on" => Ok(true),
            "0" | "false" | "no" | "off" => Ok(false),
            _ => Err(ZtError::new(format!("{key} must be a boolean"), 2)),
        };
    }
    Err(ZtError::new(format!("{key} must be a boolean"), 2))
}

fn value_as_string_list(value: &TomlValue, key: &str) -> ZtResult<Vec<String>> {
    if let Some(text) = value.as_str() {
        return Ok(text
            .split(',')
            .filter(|item| !item.is_empty())
            .map(ToString::to_string)
            .collect());
    }
    if let Some(array) = value.as_array() {
        let mut values = Vec::new();
        for item in array {
            values.push(
                item.as_str()
                    .ok_or_else(|| ZtError::new(format!("{key} must be a string list"), 2))?
                    .to_string(),
            );
        }
        return Ok(values);
    }
    Err(ZtError::new(format!("{key} must be a string list"), 2))
}

fn config_json(config: &Config) -> serde_json::Value {
    json!({
        "host": config.host,
        "transport": config.transport.as_str(),
        "picker": config.picker.as_str(),
        "remote_path": config.remote_path,
        "connect_timeout": config.connect_timeout,
        "ssh_options": config.ssh_options,
        "no_input": config.no_input,
        "config_path": config.config_path.display().to_string(),
        "config_loaded": config.config_loaded,
    })
}


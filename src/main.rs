#[derive(Debug)]
struct ZtError {
    message: String,
    code: i32,
}

impl ZtError {
    fn new(message: impl Into<String>, code: i32) -> Self {
        Self {
            message: message.into(),
            code,
        }
    }
}

impl From<io::Error> for ZtError {
    fn from(value: io::Error) -> Self {
        Self::new(value.to_string(), 1)
    }
}

type ZtResult<T> = Result<T, ZtError>;

#[derive(Clone, Debug, Eq, PartialEq)]
enum Transport {
    Ssh,
    Mosh,
}

impl Transport {
    fn parse(value: &str) -> ZtResult<Self> {
        match value.trim().to_ascii_lowercase().as_str() {
            "ssh" => Ok(Self::Ssh),
            "mosh" => Ok(Self::Mosh),
            _ => Err(ZtError::new("transport must be one of: mosh, ssh", 2)),
        }
    }

    fn as_str(&self) -> &'static str {
        match self {
            Self::Ssh => "ssh",
            Self::Mosh => "mosh",
        }
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
enum Picker {
    Auto,
    Fzf,
    Prompt,
    None,
}

impl Picker {
    fn parse(value: &str) -> ZtResult<Self> {
        match value.trim().to_ascii_lowercase().as_str() {
            "auto" => Ok(Self::Auto),
            "fzf" => Ok(Self::Fzf),
            "prompt" | "numbered" => Ok(Self::Prompt),
            "none" | "off" => Ok(Self::None),
            _ => Err(ZtError::new(
                "picker must be one of: auto, fzf, prompt, numbered, none",
                2,
            )),
        }
    }

    fn as_str(&self) -> &'static str {
        match self {
            Self::Auto => "auto",
            Self::Fzf => "fzf",
            Self::Prompt => "prompt",
            Self::None => "none",
        }
    }
}

